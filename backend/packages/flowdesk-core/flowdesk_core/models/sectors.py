"""Sector themes and stock relationship models."""

from datetime import datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    DateTime,
    Float,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import ARRAY
from sqlalchemy.orm import Mapped, mapped_column

from flowdesk_core.database import Base


class SectorTheme(Base):
    """Sector or AI-generated thematic group.

    Rows with theme_type='static_gics' are the 11 GICS sectors — seeded once,
    refreshed daily (stock_count, avg_sentiment, top_symbols).
    Rows with theme_type='dynamic_ai' are generated by generate_dynamic_themes
    from recurring theme_tags in market_signals.
    """

    __tablename__ = "sector_themes"
    __table_args__ = (
        UniqueConstraint("name", "theme_type", name="uq_sector_theme_name_type"),
        Index("ix_sector_theme_type", "theme_type"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    name: Mapped[str] = mapped_column(String(100), nullable=False)
    name_cn: Mapped[str | None] = mapped_column(String(100))
    theme_type: Mapped[str] = mapped_column(String(20), nullable=False)
    # 'static_gics' | 'dynamic_ai'

    description: Mapped[str | None] = mapped_column(Text)
    description_cn: Mapped[str | None] = mapped_column(Text)
    icon_key: Mapped[str | None] = mapped_column(String(30))
    # Maps to a frontend icon: energy | materials | industrials | consumer_disc |
    # consumer_staples | health_care | financials | technology | communication |
    # utilities | real_estate | ai_theme

    stock_count: Mapped[int] = mapped_column(Integer, default=0)
    avg_sentiment: Mapped[float | None] = mapped_column(Float)
    # Latest avg_sentiment from sector_intelligence (may be None if no signals yet)

    top_symbols: Mapped[list[str] | None] = mapped_column(ARRAY(String(20)))
    # Top 5 stocks by market_cap in this sector
    top_themes: Mapped[list[str] | None] = mapped_column(ARRAY(String(100)))
    # Top theme_tags from recent market_signals for this sector

    region: Mapped[str] = mapped_column(String(10), default="GLOBAL")
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)

    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, default=datetime.utcnow, onupdate=datetime.utcnow
    )

    def __repr__(self) -> str:
        return f"<SectorTheme {self.name} ({self.theme_type})>"


class ThemeStock(Base):
    """Many-to-many link between dynamic AI themes and their member stocks.

    Only used for dynamic_ai themes — static_gics membership is derived
    from stocks.sector at query time.
    """

    __tablename__ = "theme_stocks"
    __table_args__ = (
        UniqueConstraint("theme_id", "symbol", name="uq_theme_stock"),
        Index("ix_theme_stock_symbol", "symbol"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    theme_id: Mapped[int] = mapped_column(Integer, nullable=False, index=True)
    # FK to sector_themes.id (not enforced at ORM level for performance)
    symbol: Mapped[str] = mapped_column(String(20), nullable=False)
    score: Mapped[float | None] = mapped_column(Float)
    # Relevance score 0.0–1.0 based on signal frequency and sentiment strength
    added_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)

    def __repr__(self) -> str:
        return f"<ThemeStock theme={self.theme_id} symbol={self.symbol}>"


class StockRelationship(Base):
    """Pairwise relationship between two stocks.

    Populated by compute_stock_relationships (weekly, Saturday 03:00 UTC).
    relationship_type='sector_peer' is derived from price correlation.
    Other types may be AI-inferred in future phases.
    """

    __tablename__ = "stock_relationships"
    __table_args__ = (
        UniqueConstraint("symbol_a", "symbol_b", "relationship_type", name="uq_stock_rel"),
        Index("ix_stock_rel_a", "symbol_a"),
        Index("ix_stock_rel_b", "symbol_b"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    symbol_a: Mapped[str] = mapped_column(String(20), nullable=False)
    symbol_b: Mapped[str] = mapped_column(String(20), nullable=False)
    relationship_type: Mapped[str] = mapped_column(String(30), nullable=False)
    # 'sector_peer' | 'competitor' | 'supply_chain' | 'correlated'

    strength: Mapped[float | None] = mapped_column(Float)
    # 0.0–1.0 overall relationship strength
    correlation_30d: Mapped[float | None] = mapped_column(Float)
    # Pearson correlation of daily returns over 30 days
    correlation_90d: Mapped[float | None] = mapped_column(Float)
    # Pearson correlation of daily returns over 90 days
    direction: Mapped[str | None] = mapped_column(String(10))
    # 'positive' | 'negative'
    source: Mapped[str] = mapped_column(String(20), default="price_correlation")
    # 'price_correlation' | 'ai' | 'manual'

    computed_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)

    def __repr__(self) -> str:
        return f"<StockRelationship {self.symbol_a}↔{self.symbol_b} ({self.relationship_type})>"
